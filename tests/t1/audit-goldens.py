#!/usr/bin/env python3
"""List each T1 golden change with its controlling semantic rule.

Run after the sanctioned UPDATE=1 test generators. This reports changes;
it never regenerates expectations or establishes correctness by itself.
"""
import argparse
import difflib
from pathlib import Path
import subprocess

RULES = {
    'L': 'literal-types decision 4: "No widening, no template literal types, no literal arithmetic." Literal leaves retain their value; existing principal inference propagates them through tuples, lists, calls, returns and errors.',
    'P': 'literal-types decision 6: "A literal pattern gets its literal type only in a match." Rule 11 unions those values; fitted/shared places keep their whole head.',
    'K': 'literal-types decision 7: "Rule 13 does not use value sets." Its covariant bounds keep whole scalars and noncovariant parts become fresh holes; known results stay separate.',
    'E': 'literal-types decision 8: "E0520 compares value sets." Section 5.4 specifies constant/finite-set messages, False for == and True for !=; only top members are compared.',
    'C': 'literal-types section 5.5: "For a finite column, the missing literal." Listed values specialize first; infinite Int/String columns use the specified concrete witness. Finite scalar clauses can therefore be exhaustive.',
    'W': 'literal-types section 5.3: "When the subject ... has a type with one value, add ... the value matched is always"; usefulness also excludes rows after a covering row.',
    'N': 'literal-types section 5.3 rule 12: "The catch-all gets B - H." Only unguarded rows covering the entire candidate row contribute values; type-test complements retain their scalar head.',
    'F': 'types-joint section 9 T1 step 7: "Implement fitted choices for one clause, replacing E0235"; they add Assert for a possible failure, are not generalized, and do not apply subject constructor flow narrowing.',
}


def rule(line, path):
    if 'E0235' in line:
        return 'F'
    if 'E0520' in line:
        return 'E'
    if 'E0516' in line:
        return 'C'
    if 'W0501' in line:
        return 'W'
    if 'identity_pair :' in line or 'total_pair :' in line:
        return 'L,K'
    if any(word in line for word in ('rest :', 'literal :', 'narrow', 'except', 'remainder :')):
        return 'L,N'
    if any(word in line for word in ('digit :', 'ints :', 'strings :', 'guarded_only :', 'shared :', 'shared_tuple :', 'inferred :')):
        return 'L,P'
    return 'L'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base',default='b2cfa94')
    parser.add_argument('--write',type=Path)
    args=parser.parse_args()
    names=subprocess.check_output(['git','ls-files','--cached','--others','--exclude-standard','--','*.out'],text=True).splitlines()
    rows=[]
    for name in sorted(set(names)):
        old=subprocess.run(['git','show',f'{args.base}:{name}'],capture_output=True,text=True)
        before=old.stdout.splitlines() if old.returncode==0 else []
        after=Path(name).read_text().splitlines()
        diff=difflib.SequenceMatcher(a=before,b=after,autojunk=False)
        for tag,a,b,c,d in diff.get_opcodes():
            if tag=='equal': continue
            for kind,lines,start in [('removed',before[a:b],a),('added',after[c:d],c)]:
                for offset,line in enumerate(lines):
                    rows.append((name,start+offset+1,kind,line,rule(line,name)))
    result=['# T1 golden rule audit','', 'Generated by `python3 tests/t1/audit-goldens.py --write tests/t1-golden-rules.md` after UPDATE=1. Each line was reviewed against the corresponding source program; this inventory is not an independent expectation oracle.','']
    for key,value in RULES.items(): result += [f'- **{key}**: {value}']
    result += ['', '| File:line | Change | Text | Required by |','|---|---|---|---|']
    for name,number,kind,line,why in rows:
        line=line.replace('|','&#124;').replace('`','&#96;')
        result.append(f'| {name}:{number} | {kind} | {line} | {why} |')
    result += ['',f'{len(rows)} changed lines across {len(set(r[0] for r in rows))} outputs.','']
    text='\n'.join(result)
    if args.write: args.write.write_text(text)
    else: print(text)

if __name__=='__main__': main()
