#!/usr/bin/env python3
"""Generate independent public-API tests from the pinned Unicode 17 oracle data.

Expected values come from Unicode's test files, never the Wleam implementation.
This script requires only Python's standard library and performs no downloads.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
DATA = ROOT / "stdlib" / "unicode" / "data"
VERSION = "17.0.0"
HEADER = "// Generated by tests/unicode/generate.py; edit the generator instead.\n"


def literal(codepoints: list[int] | tuple[int, ...] | str) -> str:
    if isinstance(codepoints, str):
        codepoints = [ord(char) for char in codepoints]
    return '"' + "".join(f"\\u{{{value:x}}}" for value in codepoints) + '"'


def grapheme_cases() -> list[dict]:
    source = DATA / "auxiliary" / "GraphemeBreakTest.txt"
    text = source.read_text(encoding="utf-8")
    if f"GraphemeBreakTest-{VERSION}.txt" not in text.splitlines()[0]:
        raise ValueError("Grapheme corpus version does not match Unicode 17.0.0")
    cases = []
    for line_number, line in enumerate(text.splitlines(), 1):
        body = line.partition("#")[0].strip()
        if not body:
            continue
        tokens = body.split()
        if tokens[0] != "÷" or tokens[-1] != "÷" or len(tokens) % 2 != 1:
            raise ValueError(f"Malformed GraphemeBreakTest line {line_number}")
        clusters: list[list[int]] = []
        cluster: list[int] = []
        for index in range(1, len(tokens), 2):
            codepoint = int(tokens[index], 16)
            if 0xD800 <= codepoint <= 0xDFFF or codepoint > 0x10FFFF:
                raise ValueError(f"Non-scalar codepoint on line {line_number}")
            cluster.append(codepoint)
            boundary = tokens[index + 1]
            if boundary == "÷":
                clusters.append(cluster)
                cluster = []
            elif boundary != "×":
                raise ValueError(f"Unknown boundary on line {line_number}")
        if cluster:
            raise ValueError(f"Missing final boundary on line {line_number}")
        cases.append({"line": line_number, "clusters": clusters})
    if not cases:
        raise ValueError("Empty GraphemeBreakTest corpus")
    return cases


def casing_cases() -> list[dict]:
    mappings: dict[int, tuple[list[int], list[int]]] = {}
    for line in (DATA / "UnicodeData.txt").read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        codepoint = int(fields[0], 16)
        upper = [int(fields[12], 16)] if fields[12] else [codepoint]
        lower = [int(fields[13], 16)] if fields[13] else [codepoint]
        if upper != [codepoint] or lower != [codepoint]:
            mappings[codepoint] = (lower, upper)
    special = (DATA / "SpecialCasing.txt").read_text(encoding="utf-8")
    if f"SpecialCasing-{VERSION}.txt" not in special.splitlines()[0]:
        raise ValueError("Casing data version does not match Unicode 17.0.0")
    for line in special.splitlines():
        body = line.partition("#")[0].strip()
        if not body:
            continue
        fields = [field.strip() for field in body.split(";")]
        if fields[4]:  # Locale/context-sensitive rows are tested separately below.
            continue
        codepoint = int(fields[0], 16)
        lower = [int(part, 16) for part in fields[1].split()]
        upper = [int(part, 16) for part in fields[3].split()]
        mappings[codepoint] = (lower, upper)
    return [
        {"source": [codepoint], "lower": lower, "upper": upper}
        for codepoint, (lower, upper) in sorted(mappings.items())
    ]


# The default case algorithm uses the original input as context, skips
# Case_Ignorable characters, and does not select Turkish/Lithuanian locales.
CONTEXT_CASES = [
    ("ΟΣ", "ος", "ΟΣ"),
    ("ΟΣΑ", "οσα", "ΟΣΑ"),
    ("ΟΣ\u0301", "ος\u0301", "ΟΣ\u0301"),
    ("Ο\u0301Σ", "ο\u0301ς", "Ο\u0301Σ"),
    ("Ο'Σ", "ο'ς", "Ο'Σ"),
    ("ΟΣ'Α", "οσ'α", "ΟΣ'Α"),
    ("Σ", "σ", "Σ"),
    ("ΣΣ", "σς", "ΣΣ"),
    ("Σ.Σ", "σ.ς", "Σ.Σ"),
    ("Ο Σ", "ο σ", "Ο Σ"),
    ("\u0345Σ", "\u0345σ", "ΙΣ"),
    ("Ο\u0345Σ", "ο\u0345ς", "ΟΙΣ"),
    ("ΟΣ\u0345", "ος\u0345", "ΟΣΙ"),
    ("Iİıi", "ii\u0307ıi", "IİII"),
    ("Straße", "straße", "STRASSE"),
    ("\uFB03", "\uFB03", "FFI"),
    ("\u0390", "\u0390", "Ι\u0308\u0301"),
    ("A\u0000Σ", "a\u0000σ", "A\u0000Σ"),
]


def grouped_tests(prefix: str, bodies: list[list[str]], chunk_size: int = 32) -> str:
    parts = [HEADER, "import gleam/string\n\n"]
    for chunk in range(0, len(bodies), chunk_size):
        parts.append(f"pub fn {prefix}_{chunk // chunk_size:04}_test() {{\n")
        for body in bodies[chunk : chunk + chunk_size]:
            parts.extend(f"  {line}\n" for line in body)
        parts.append("}\n\n")
    return "".join(parts)


def generated_files() -> dict[Path, str]:
    graphemes = grapheme_cases()
    casing = casing_cases()
    grapheme_bodies = []
    for case in graphemes:
        clusters = case["clusters"]
        source = [cp for cluster in clusters for cp in cluster]
        expected = "[" + ", ".join(literal(cluster) for cluster in clusters) + "]"
        grapheme_bodies.append([
            f"// GraphemeBreakTest.txt:{case['line']}",
            f"assert string.to_graphemes({literal(source)}) == {expected}",
            f"assert string.length({literal(source)}) == {len(clusters)}",
        ])
    casing_bodies = [
        [
            f"assert string.lowercase({literal(case['source'])}) == {literal(case['lower'])}",
            f"assert string.uppercase({literal(case['source'])}) == {literal(case['upper'])}",
        ]
        for case in casing
    ]
    contextual_bodies = [
        [
            f"assert string.lowercase({literal(source)}) == {literal(lower)}",
            f"assert string.uppercase({literal(source)}) == {literal(upper)}",
        ]
        for source, lower, upper in CONTEXT_CASES
    ]
    contextual_bodies.append([
        'assert string.to_graphemes("") == []',
        'assert string.length("") == 0',
        'assert string.lowercase("") == ""',
        'assert string.uppercase("") == ""',
    ])
    sources = [
        "auxiliary/GraphemeBreakTest.txt",
        "UnicodeData.txt",
        "SpecialCasing.txt",
    ]
    summary = {
        "unicode_version": VERSION,
        "grapheme_cases": len(graphemes),
        "casing_scalar_cases": len(casing),
        "contextual_casing_cases": len(CONTEXT_CASES),
        "test_functions": (len(graphemes) + 31) // 32 + (len(casing) + 31) // 32 + 1,
        "inputs": {
            name: hashlib.sha256((DATA / name).read_bytes()).hexdigest()
            for name in sources
        },
    }
    return {
        HERE / "test" / "grapheme_break_test.gleam": grouped_tests("grapheme_break", grapheme_bodies),
        HERE / "test" / "casing_test.gleam": grouped_tests("casing", casing_bodies),
        HERE / "test" / "contextual_casing_test.gleam": grouped_tests("contextual_casing", contextual_bodies),
        HERE / "corpus.json": json.dumps(summary, indent=2, sort_keys=True) + "\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files without writing")
    args = parser.parse_args()
    stale = []
    files = generated_files()
    for path, content in files.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        for path in stale:
            print(f"out of date: {path}")
        return 1
    print(f"Unicode {VERSION}: {len(files)} generated files {'verified' if args.check else 'written'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
