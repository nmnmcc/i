#!/usr/bin/env python3
"""Independent integer model and vector generator for spec §9.10.

Run with UPDATE=1 to regenerate vectors.i. Otherwise verify its generated tokens, ignoring layout and separators.
Constants and the first three seed-1337 words are from the pinned primary source:
https://hackage-content.haskell.org/package/splitmix-0.1.3.1/docs/src/System.Random.SplitMix.html
All other vectors are computed here from §9.10, not copied from i execution.
The model uses Python integers, strings for tree addresses, and tuple states.
"""
import os
from pathlib import Path

W = 1 << 64
MASK = W - 1
GOLDEN = 0x9E3779B97F4A7C15


def murmur(x):
    x %= W
    for shift, multiplier in [(33, 0xFF51AFD7ED558CCD),
                              (33, 0xC4CEB9FE1A85EC53)]:
        x = ((x ^ (x >> shift)) * multiplier) % W
    return x ^ (x >> 33)


def stafford(x):
    x %= W
    for shift, multiplier in [(30, 0xBF58476D1CE4E5B9),
                              (27, 0x94D049BB133111EB)]:
        x = ((x ^ (x >> shift)) * multiplier) % W
    return x ^ (x >> 31)


def gamma(x):
    z = stafford(x) | 1
    return z ^ (0xAAAAAAAAAAAAAAAA if (z ^ (z >> 1)).bit_count() < 24 else 0)


def initial(seed):
    return murmur(seed), gamma(seed + GOLDEN)


def draw(state):
    s, g = state
    s = (s + g) % W
    return murmur(s), (s, g)


def native_split(state):
    s, g = state
    return ((s + 2 * g) % W, g), (murmur(s + g), gamma(s + 2 * g))


def navigate(state, code):
    for bit in code:
        continuation, first = native_split(state)
        _, second = native_split(continuation)
        state = (first, second)[int(bit)]
    return state


def path_code(i):
    digits = bin(i)[2:]
    return '1' + '0' * (len(digits) - 1) + digits


def bounded(state, n):
    k = max(1, ((n - 1).bit_length() + 63) // 64)
    space = W ** k
    limit = space - space % n
    used = 0
    while True:
        value = 0
        for j in range(k):
            u, state = draw(state)
            value += u << (64 * j)
            used += 1
        if value < limit:
            return value % n, state, used


def check_reference():
    # Published source doctests, independent of the derived vector file.
    assert initial(42) == (9297814886316923340, 13679457532755275413)
    state = initial(1337)
    for expected in (0xB5C19E300E8B07B3, 0xD600E0E216C0AC76, 0xC54EFC3B3CC5AF29):
        value, state = draw(state)
        assert value == expected
    # §9.10's correction branch: V(0)=0, z=1, one transition <24.
    assert initial(-GOLDEN)[1] == 0xAAAAAAAAAAAAAAAB
    # Seed 12 exercises the highest reachable odd transition count below 24.
    z = stafford(12 + GOLDEN) | 1
    assert (z ^ (z >> 1)).bit_count() == 23
    assert initial(12)[1] == z ^ 0xAAAAAAAAAAAAAAAA
    # Exhaustive small-word substitute: every residue occurs equally often in
    # the accepted region. This proves the partition arithmetic, not PRNG quality.
    cases = 0
    for bits in range(1, 9):
        size = 1 << bits
        for n in range(1, size + 1):
            limit = size - size % n
            counts = [0] * n
            for u in range(limit):
                counts[u % n] += 1
            assert len(set(counts)) == 1
            cases += 1
    # Prefix-free domain tags, including arbitrary-size indices.
    codes = ['00', '01'] + [path_code(i) for i in range(1, 1025)]
    codes += [path_code((1 << 200) + 1)]
    for a in codes:
        assert not any(b.startswith(a) for b in codes if a != b)
    return cases


def generate():
    out = ['// spec: 9.10', '// expect: pass', '',
           '// Generated by UPDATE=1 python3 tests/spec/9.10/reference.py.',
           '// The pinned source supplies constants and seed-1337 doctest words.',
           '// Other values are independently computed from spec §9.10; see reference.py.',
           '(testlib = (test) = std/test, i/random, i/core)', '',
           'advance = (g: random.Generator, n: Int) -> random.Generator {',
           '\t{ n == 0 } |> {', '\t\tTrue -> g',
           '\t\tFalse -> advance(random.word(g).1, n - 1)', '\t}', '}', '']
    def test(name, body):
        out.extend(['test(' + repr(name).replace(chr(39), chr(34)) + ', () {'] + ['\t' + s for s in body] + ['\tNil', '})', ''])
    # Include negative/oversized seeds and a forced low-transition correction.
    for j, seed in enumerate([0, 42, 1337, -1, -(1 << 200) - 17, -GOLDEN, 12]):
        state = initial(seed)
        body = [f'g0 = random.from_seed({seed})']
        for i in range(8):
            value, state = draw(state)
            body += [f'(u{i}, g{i+1}) = random.word(g{i})', f'assert(u{i} == 0x{value:016x})']
        test(f'words_{j}', body)
    # Codes and derived words must be checked independently, not only inequality.
    derivations = [('s1', 'random.split(g).0', '00'),
                   ('s2', 'random.split(g).1', '01'),
                   ('p1', 'random.at_path(g, [1])', '11'),
                   ('p2', 'random.at_path(g, [2])', '1010'),
                   ('p3', 'random.at_path(g, [3])', '1011'),
                   ('mixed', 'random.at_path(random.split(g).0, [2, 1])', '00' + path_code(2) + path_code(1)),
                   ('drawn', 'random.split(random.word(g).1).1', None),
                   ('large', f'random.at_path(g, [{(1 << 200) + 1}])', path_code((1 << 200) + 1))]
    for name, expression, code in derivations:
        state = initial(0)
        if code is None:
            _, state = draw(state)
            code = '01'
        state = navigate(state, code)
        body = ['g = random.from_seed(0)', f'h0 = {expression}']
        for i in range(4):
            value, state = draw(state)
            body += [f'(u{i}, h{i+1}) = random.word(h{i})', f'assert(u{i} == 0x{value:016x})']
        test('tree_' + name, body)
    # Actual rejection near W/2, and near W^2/2, catches missing/reordered draws.
    # Plus the boundaries W-1, W, W+1 and a 193-bit bound.
    for j, n in enumerate([1, 3, W - 1, W, W + 1, W // 2 + 1,
                            W * W // 2 + 1, (1 << 193) + 123]):
        state = initial(0)
        body = ['g0 = random.from_seed(0)']
        rejections = 0
        for i in range(4):
            value, state, used = bounded(state, n)
            k = max(1, ((n - 1).bit_length() + 63) // 64)
            rejections += used // k - 1
            body += [f'(u{i}, g{i+1}) = random.int(g{i}, {n})',
                     f'assert(u{i} == {value})',
                     f'assert(g{i+1} == advance(g{i}, {used}))']
        if n in [W // 2 + 1, W * W // 2 + 1]:
            assert rejections > 0
        test(f'bounded_{j}', body)
    return '\n'.join(out)


def main():
    cases = check_reference()
    target = Path(__file__).with_name('vectors.i')
    text = generate()
    if os.environ.get('UPDATE') == '1':
        target.write_text(text)
        print(f'Generated {target}')
    else:
        # Formatting is performed by the repository formatter when generating.
        # Whitespace does not affect any generated expectation or its source.
        assert ''.join(target.read_text().split()).replace(',', '') == ''.join(text.split()).replace(',', '')
        print('Generated vectors match the independent model')
    print(f'Published vectors, weak gamma, prefix codes, {cases} exhaustive rejection partitions: pass')


if __name__ == '__main__':
    main()
