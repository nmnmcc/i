#!/usr/bin/env python3
"""Generate Wleam's Unicode 17 tables from the checked-in, hashed UCD files.

No network access is required. Run with --check in CI to verify that all source
hashes match and that the checked-in Gleam files have been regenerated.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess


HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
DATA = HERE / "data"
TABLES = HERE.parent / "src/gleam/wleam_unicode_tables.gleam"
TESTS = ROOT / "tests/stdlib/string_unicode_generated_test.gleam"

GCB = {
    "Other": 0,
    "CR": 1,
    "LF": 2,
    "Control": 3,
    "Extend": 4,
    "ZWJ": 5,
    "Regional_Indicator": 6,
    "Prepend": 7,
    "SpacingMark": 8,
    "L": 9,
    "V": 10,
    "T": 11,
    "LV": 12,
    "LVT": 13,
}
INCB = {"None": 0, "Consonant": 1, "Extend": 2, "Linker": 3}


def validate_sources() -> None:
    manifest = json.loads((HERE / "manifest.json").read_text())
    assert manifest["unicode_version"] == "17.0.0"
    for name, source in manifest["sources"].items():
        actual = hashlib.sha256((DATA / name).read_bytes()).hexdigest()
        if actual != source["sha256"]:
            raise ValueError(f"Unicode source hash mismatch: {name}")
    license_hash = hashlib.sha256((HERE / "LICENSE.txt").read_bytes()).hexdigest()
    if license_hash != manifest["license"]["sha256"]:
        raise ValueError("Unicode license hash mismatch")


def rows(name: str):
    for line in (DATA / name).read_text().splitlines():
        record = line.split("#", 1)[0].strip()
        if record:
            yield [part.strip() for part in record.split(";")]


def span(value: str) -> tuple[int, int]:
    ends = value.split("..")
    return int(ends[0], 16), int(ends[-1], 16)


def coalesce(ranges: list[tuple[int, int, int]]) -> list[tuple[int, int, int]]:
    merged: list[tuple[int, int, int]] = []
    for start, end, value in sorted(ranges):
        if merged and start <= merged[-1][1]:
            raise ValueError(f"Overlapping property ranges at U+{start:04X}")
        if merged and start == merged[-1][1] + 1 and value == merged[-1][2]:
            merged[-1] = merged[-1][0], end, value
        else:
            merged.append((start, end, value))
    return merged


def property_ranges(name: str, property_name: str) -> list[tuple[int, int, int]]:
    return coalesce(
        [(*span(row[0]), 1) for row in rows(name) if row[1] == property_name]
    )


def load_tables():
    properties = {
        "grapheme_break": coalesce(
            [(*span(row[0]), GCB[row[1]]) for row in rows("auxiliary/GraphemeBreakProperty.txt")]
        ),
        "indic_conjunct_break": coalesce(
            [
                (*span(row[0]), INCB[row[2]])
                for row in rows("DerivedCoreProperties.txt")
                if row[1] == "InCB"
            ]
        ),
        "extended_pictographic": property_ranges("emoji/emoji-data.txt", "Extended_Pictographic"),
        "cased": property_ranges("DerivedCoreProperties.txt", "Cased"),
        "case_ignorable": property_ranges("DerivedCoreProperties.txt", "Case_Ignorable"),
        "pattern_whitespace": property_ranges("PropList.txt", "Pattern_White_Space"),
    }
    lowercase: dict[int, list[int]] = {}
    uppercase: dict[int, list[int]] = {}
    for row in rows("UnicodeData.txt"):
        cp = int(row[0], 16)
        if row[12]:
            uppercase[cp] = [int(row[12], 16)]
        if row[13]:
            lowercase[cp] = [int(row[13], 16)]
    for row in rows("SpecialCasing.txt"):
        cp = int(row[0], 16)
        if not row[4]:
            lowercase[cp] = [int(value, 16) for value in row[1].split()]
            uppercase[cp] = [int(value, 16) for value in row[3].split()]
        elif not any(locale in row[4].split() for locale in ("tr", "az", "lt")):
            # Locale-independent contextual casing is implemented in the algorithm.
            if cp != 0x03A3 or row[4] != "Final_Sigma":
                raise ValueError(f"Unhandled locale-independent conditional casing: {row}")
    mappings = {
        "lowercase_mapping": {cp: value for cp, value in lowercase.items() if value != [cp]},
        "uppercase_mapping": {cp: value for cp, value in uppercase.items() if value != [cp]},
    }
    return properties, mappings


HEADER = """// Generated by stdlib/unicode/generate.py; do not edit.
// Unicode 17.0.0, UAX #29 revision 47.
// Unicode data: copyright Unicode, Inc.; see stdlib/unicode/LICENSE.txt.
// Source URLs and SHA-256 digests: stdlib/unicode/manifest.json.
"""


def generate_tables(properties, mappings) -> str:
    # These are data, rather than thousands of generated branches. The compiler
    # emits each constant as bytes; table lookup stays logarithmic and the code
    # is shared by every Unicode property/case mapping.
    out = [HEADER, "// Range records: start:u32, end:u32, property:u8, all big-endian."]
    for name, ranges in properties.items():
        is_boolean = name not in ("grapheme_break", "indic_conjunct_break")
        result_type = "Bool" if is_boolean else "Int"
        out.append(f"const {name}_data = <<")
        for start, end, value in ranges:
            out.append(f"  {start}:32, {end}:32, {value}:8,")
        out += [">>", ""]
        out.append(f"pub fn {name}(cp: Int) -> {result_type} {{")
        suffix = " == 1" if is_boolean else ""
        out.append(f"  range_lookup({name}_data, cp, 0, {len(ranges)}){suffix}")
        out += ["}", ""]
    out.append("// Case records: scalar:u32, count:u8, first:u32, second:u32, third:u32.")
    for name, mapping in mappings.items():
        out.append(f"const {name}_data = <<")
        for cp, values in sorted(mapping.items()):
            if not 1 <= len(values) <= 3:
                raise ValueError(f"Unsupported full case mapping length for U+{cp:04X}")
            first, second, third = values + [0] * (3 - len(values))
            out.append(f"  {cp}:32, {len(values)}:8, {first}:32, {second}:32, {third}:32,")
        out += [">>", ""]
        out.append(f"pub fn {name}(cp: Int) -> List(Int) {{")
        out.append(f"  case_lookup({name}_data, cp, 0, {len(mapping)})")
        out += ["}", ""]
    out.append('''fn range_lookup(table: BitArray, cp: Int, low: Int, high: Int) -> Int {
  case low >= high {
    True -> 0
    False -> {
      let middle = { low + high } / 2
      let offset = middle * 9
      let assert <<_:size(offset)-bytes, start:32, end:32, value:8, _:bits>> = table
      case cp < start {
        True -> range_lookup(table, cp, low, middle)
        False -> {
          case cp > end {
            True -> range_lookup(table, cp, middle + 1, high)
            False -> value
          }
        }
      }
    }
  }
}

fn case_lookup(table: BitArray, cp: Int, low: Int, high: Int) -> List(Int) {
  case low >= high {
    True -> [cp]
    False -> {
      let middle = { low + high } / 2
      let offset = middle * 17
      let assert <<_:size(offset)-bytes, scalar:32, count:8,
        first:32, second:32, third:32, _:bits>> = table
      case cp < scalar {
        True -> case_lookup(table, cp, low, middle)
        False -> {
          case cp > scalar {
            True -> case_lookup(table, cp, middle + 1, high)
            False -> {
              case count {
                1 -> [first]
                2 -> [first, second]
                _ -> [first, second, third]
              }
            }
          }
        }
      }
    }
  }
}
''')
    return "\n".join(out)


def grapheme_cases():
    for line_number, line in enumerate((DATA / "auxiliary/GraphemeBreakTest.txt").read_text().splitlines(), 1):
        record = line.split("#", 1)[0].strip()
        if not record:
            continue
        clusters: list[list[int]] = []
        cluster: list[int] = []
        for item in record.split():
            if item == "÷":
                if cluster:
                    clusters.append(cluster)
                    cluster = []
            elif item != "×":
                cluster.append(int(item, 16))
        if cluster:
            clusters.append(cluster)
        yield line_number, clusters


def literal(codepoints: list[int]) -> str:
    return '"' + "".join(f"\\u{{{cp:x}}}" for cp in codepoints) + '"'


def generate_tests(mappings) -> str:
    out = [HEADER, "import gleam/wleam_unicode as unicode", ""]
    cases = list(grapheme_cases())
    for offset in range(0, len(cases), 24):
        out.append(f"pub fn unicode_grapheme_break_{offset // 24:03d}_test() {{")
        for line, clusters in cases[offset : offset + 24]:
            text = literal([cp for cluster in clusters for cp in cluster])
            expected = "[" + ", ".join(literal(cluster) for cluster in clusters) + "]"
            out += [f"  // GraphemeBreakTest.txt:{line}", f"  assert unicode.graphemes({text}) == {expected}"]
        out += ["}", ""]
    for name, mapping in mappings.items():
        function = name.removesuffix("_mapping")
        cases = sorted(mapping.items())
        for offset in range(0, len(cases), 24):
            out.append(f"pub fn unicode_{function}_{offset // 24:03d}_test() {{")
            for cp, result in cases[offset : offset + 24]:
                out.append(f"  assert unicode.{function}({literal([cp])}) == {literal(result)}")
            out += ["}", ""]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated sources without editing")
    parser.add_argument("--formatter", default=os.environ.get("GLEAM_BIN", "gleam"), help="path to the pinned Gleam 1.19.2 formatter")
    arguments = parser.parse_args()
    validate_sources()
    version = subprocess.check_output([arguments.formatter, "--version"], text=True).strip()
    if version != "gleam 1.19.2":
        raise SystemExit(f"Expected the pinned Gleam 1.19.2 formatter, got {version!r}")
    properties, mappings = load_tables()
    outputs = {TABLES: generate_tables(properties, mappings), TESTS: generate_tests(mappings)}
    for path, content in outputs.items():
        content = subprocess.check_output([arguments.formatter, "format", "--stdin"], input=content, text=True)
        if arguments.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Generated Unicode file is stale: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    counts = {name: len(ranges) for name, ranges in properties.items()}
    counts.update({name: len(mapping) for name, mapping in mappings.items()})
    print(json.dumps({"unicode": "17.0.0", "ranges_and_mappings": counts, "grapheme_cases": len(list(grapheme_cases()))}, sort_keys=True))


if __name__ == "__main__":
    main()
