function describe(value) {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "bigint") return `${value}`;
  if (value && value.bytes instanceof Uint8Array) return `<<${[...value.bytes].join(", ")}>> (${value.bitLength} bits)`;
  return String(value);
}

function expect(condition, message) {
  if (!condition) throw new AbiError(message);
}

function leb(value) {
  const bytes = [];
  do {
    const byte = value & 0x7f;
    value >>>= 7;
    bytes.push(byte | (value ? 0x80 : 0));
  } while (value);
  return bytes;
}

// Importing an exported Wasm function performs an exact function-type check.
// This tiny module also gives a JavaScript callback a concrete Wasm signature,
// so linking it into the guest checks metadata against the guest's imports.
function typedFunction(fn, params, results, location) {
  const key = `${params.join(",")}:${results.join(",")}`;
  let module = signatureModules.get(key);
  if (!module) {
    const section = (id, bytes) => [id, ...leb(bytes.length), ...bytes];
    module = new WebAssembly.Module(Uint8Array.from([
      0, 97, 115, 109, 1, 0, 0, 0,
      ...section(1, [1, 0x60, ...leb(params.length), ...params, ...leb(results.length), ...results]),
      ...section(2, [1, 1, 97, 1, 102, 0, 0]), // import a.f with type 0
      ...section(7, [1, 1, 102, 0, 0]), // export f, the imported function
    ]));
    signatureModules.set(key, module);
  }
  try {
    return new WebAssembly.Instance(module, { a: { f: fn } }).exports.f;
  } catch (cause) {
    throw new AbiError(`Wasm signature does not match ABI descriptor for ${location}`, { cause });
  }
}

// The import of a host function: a tiny Wasm function that calls the
// JavaScript callback, then asks `broken` whether the callback failed, and
// traps when it did. A JavaScript exception is never thrown into the module:
// the callback catches everything, and a trap runs no handler of the module. The callback gives results of the right types also when it fails.
const guardModules = new Map();
function guardedFunction(fn, broken, params, results, location) {
  const key = `${params.join(",")}:${results.join(",")}`;
  let module = guardModules.get(key);
  if (!module) {
    const section = (id, bytes) => [id, ...leb(bytes.length), ...bytes];
    const body = [
      0, // no locals
      ...params.flatMap((_, index) => [0x20, ...leb(index)]), // local.get
      0x10, 0, // call the callback
      0x10, 1, // call broken
      0x04, 0x40, 0x00, 0x0b, // if (then unreachable)
      0x0b,
    ];
    module = new WebAssembly.Module(Uint8Array.from([
      0, 97, 115, 109, 1, 0, 0, 0,
      ...section(1, [2, 0x60, ...leb(params.length), ...params, ...leb(results.length), ...results, 0x60, 0, 1, 0x7f]),
      ...section(2, [2, 1, 97, 1, 102, 0, 0, 1, 97, 1, 98, 0, 1]), // import a.f with type 0, a.b with type 1
      ...section(3, [1, 0]),
      ...section(7, [1, 1, 102, 0, 2]), // export f, the guard
      ...section(10, [1, ...leb(body.length), ...body]),
    ]));
    guardModules.set(key, module);
  }
  try {
    return new WebAssembly.Instance(module, { a: { f: fn, b: broken } }).exports.f;
  } catch (cause) {
    throw new AbiError(`Wasm signature does not match ABI descriptor for ${location}`, { cause });
  }
}

function validateFunction(module, exports, name, params, results) {
  expect(typeof exports[name] === "function", `Missing exported function ${name}`);
  let signatures = checkedSignatures.get(module);
  if (!signatures) checkedSignatures.set(module, signatures = new Set());
  const key = JSON.stringify([name, params, results]);
  if (signatures.has(key)) return;
  typedFunction(exports[name], params, results, name);
  signatures.add(key);
}

const paramTypes = (signature) => signature.params.flatMap((type) => wasmTypes[type]);
