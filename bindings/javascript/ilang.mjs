function plainObject(value, location) {
  expect(value && typeof value === "object" && !Array.isArray(value), `${location} must be an object`);
  return value;
}

function only(value, fields, location) {
  for (const field of Object.keys(value)) expect(fields.includes(field), `Unknown field ${field} in ${location}`);
}

function descriptor(value, location, external = false) {
  plainObject(value, location);
  only(value, ["params", "result", "errors", "async"], location);
  expect(Array.isArray(value.params), `Invalid params at ${location}`);
  for (const type of [...value.params, value.result]) expect(kinds.has(type), `Unknown ABI type ${String(type)} at ${location}`);
  const errors = value.errors ?? [];
  expect(Array.isArray(errors), `Invalid errors at ${location}`);
  for (const type of errors) expect(canonical.includes(type), `Unknown error type ${String(type)} at ${location}`);
  for (let index = 1; index < errors.length; index++) {
    expect(canonical.indexOf(errors[index - 1]) < canonical.indexOf(errors[index]), `Errors at ${location} must be in canonical order without repeats`);
  }
  const isAsync = value.async ?? false;
  expect(typeof isAsync === "boolean", `Invalid async at ${location}`);
  if (external) expect(!errors.length && !isAsync, `${location} cannot have errors or be async`);
  return Object.freeze({ params: Object.freeze([...value.params]), result: value.result, errors: Object.freeze([...errors]), async: isAsync });
}

function entryPoint(value, location) {
  plainObject(value, location);
  only(value, ["name", "async"], location);
  expect(typeof value.name === "string", `${location} needs a name`);
  const isAsync = value.async ?? false;
  expect(typeof isAsync === "boolean", `Invalid async at ${location}`);
  return Object.freeze({ name: value.name, async: isAsync });
}

const reserved = (name) => ["memory", "ilang_alloc", "ilang_free", "ilang_start", "ilang_continue"].includes(name) || name.startsWith("ilang_resume:") || name.startsWith("ilang_result:");

function functions(value, location, external) {
  const result = Object.create(null);
  for (const [module, entries] of Object.entries(plainObject(value === undefined ? {} : value, location))) {
    expect(module !== namespace, `${namespace} is reserved for the runtime imports`);
    result[module] = Object.create(null);
    for (const [name, signature] of Object.entries(plainObject(entries, `${location} ${module}`))) {
      result[module][name] = descriptor(signature, `${location} ${module} ${name}`, external);
    }
    Object.freeze(result[module]);
  }
  return Object.freeze(result);
}

/** Reads a consumer-selected collection artifact, if present. */
export function readCollections(module) {
  const sections = WebAssembly.Module.customSections(module, "ilang.collections");
  expect(sections.length <= 1, "Duplicate ilang.collections sections");
  if (!sections.length) return null;
  let artifact;
  try { artifact = JSON.parse(decoder.decode(sections[0])); }
  catch (cause) { throw new AbiError("Malformed ilang.collections metadata", { cause }); }
  expect(artifact && typeof artifact === "object" &&
    typeof artifact.selected === "string" && typeof artifact.export === "string" &&
    typeof artifact.is_async === "boolean" && artifact.manifest &&
    typeof artifact.manifest.revision === "string" && Array.isArray(artifact.manifest.entries) &&
    artifact.manifest.entries.some((entry) => entry && entry.handle === artifact.selected),
    "Malformed ilang.collections metadata");
  return artifact;
}

/** Reads and checks the ilang.abi metadata, or the metadata `supplied` for a module without it. */
export function readAbi(module, supplied) {
  if (supplied === undefined && embeddedAbis.has(module)) return embeddedAbis.get(module);
  const sections = WebAssembly.Module.customSections(module, "ilang.abi");
  if (sections.length > 1) throw new AbiError("Duplicate ilang.abi sections");
  let embedded;
  if (sections.length) {
    try {
      embedded = JSON.parse(decoder.decode(sections[0]));
    } catch (cause) {
      throw new AbiError("Malformed ilang.abi metadata", { cause });
    }
  }
  if (sections.length && supplied !== undefined) throw new AbiError("An embedded ABI cannot be overridden");
  const value = sections.length ? embedded : supplied === undefined ? { version, entry: null, tests: [], exports: {}, services: {}, externals: {} } : supplied;
  plainObject(value, "ABI metadata");
  const fields = ["version", "entry", "tests", "exports", "services", "externals"];
  only(value, fields, "the ABI metadata");
  for (const field of fields) expect(field in value, `The ABI metadata needs the field ${field}`);
  if (typeof value.version === "number" && value.version < version) {
    throw new AbiError(`the module uses i ABI version ${value.version}; build it again with this version of i`);
  }
  if (typeof value.version === "number" && value.version > version) {
    throw new AbiError(`the module uses i ABI version ${value.version}, but this host reads version ${version}; update the host`);
  }
  if (value.version !== version) throw new AbiError(`Unsupported i ABI version ${value.version}`);
  const exports = Object.create(null);
  for (const [name, signature] of Object.entries(plainObject(value.exports === undefined ? {} : value.exports, "ABI exports"))) {
    expect(!reserved(name), `Export ${name} uses a name of the binary interface`);
    exports[name] = descriptor(signature, `export ${name}`);
  }
  const entry = value.entry === undefined || value.entry === null ? null : entryPoint(value.entry, "the ABI entry");
  expect(value.tests === undefined || Array.isArray(value.tests), "ABI tests must be an array");
  const tests = (value.tests ?? []).map((test, index) => entryPoint(test, `ABI test ${index}`));
  for (const point of [...(entry ? [entry] : []), ...tests]) {
    expect(!(point.name in exports) && !reserved(point.name), `${point.name} cannot be an entry point`);
  }
  const services = functions(value.services, "service", false);
  const externals = functions(value.externals, "external", true);
  for (const [module, entries] of Object.entries(externals)) {
    for (const name of Object.keys(entries)) expect(!services[module]?.[name], `${module} ${name} is both a service function and an external`);
  }
  const abi = Object.freeze({ version, entry, tests: Object.freeze(tests), exports: Object.freeze(exports), services, externals });
  if (supplied === undefined) embeddedAbis.set(module, abi);
  return abi;
}

function unsigned(value, label) {
  if (typeof value !== "number" || !Number.isInteger(value) || value < -0x80000000 || value > 0xffffffff) {
    throw new AbiError(`${label} must be a Wasm i32`);
  }
  return value >>> 0;
}

/** Encodes an integer without converting it through a JavaScript Number. */
export function integerToLimbs(value) {
  if (typeof value !== "bigint") throw new TypeError("Int arguments must be JavaScript bigint values");
  const sign = value < 0n ? -1 : value > 0n ? 1 : 0;
  let magnitude = value < 0n ? -value : value;
  const limbs = [];
  while (magnitude !== 0n) {
    limbs.push(Number(magnitude & 0xffffffffn));
    magnitude >>= 32n;
  }
  const bytes = new Uint8Array(limbs.length * 4);
  const view = new DataView(bytes.buffer);
  limbs.forEach((limb, index) => view.setUint32(index * 4, limb, true));
  return { sign, bytes };
}

/** Decodes the canonical sign/magnitude little-endian integer representation. */
export function integerFromLimbs(sign, bytes) {
  expect(sign === -1 || sign === 0 || sign === 1, "Invalid integer sign");
  expect(bytes instanceof Uint8Array && bytes.byteLength % 4 === 0, "Integer limbs must contain complete 32-bit words");
  expect((sign === 0) === (bytes.byteLength === 0), "Integer zero must have sign zero and no limbs");
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  if (bytes.byteLength) expect(view.getUint32(bytes.byteLength - 4, true) !== 0, "Integer magnitude has leading zero limbs");
  let value = 0n;
  for (let offset = bytes.byteLength - 4; offset >= 0; offset -= 4) {
    value = (value << 32n) | BigInt(view.getUint32(offset, true));
  }
  return sign === -1 ? -value : value;
}

function correctBits(value) {
  if (!value || !(value.bytes instanceof Uint8Array)) return false;
  const { bytes, bitLength } = value;
  if (!Number.isSafeInteger(bitLength) || bitLength < 0 || bitLength > 0xffffffff) return false;
  if (bytes.length !== Math.ceil(bitLength / 8)) return false;
  const remainder = bitLength % 8;
  return !remainder || (bytes.at(-1) & ((1 << (8 - remainder)) - 1)) === 0;
}

/**
 * Is this JavaScript value of the type, so that it can be given to the module
 * as it is, also when it is not correct? The module then checks it.
 */
function ofType(type, value) {
  switch (type) {
    case "nil": return value === undefined || value === null;
    case "bool": return typeof value === "boolean";
    case "int": return typeof value === "bigint";
    case "float": return typeof value === "number";
    case "string": return typeof value === "string";
    case "bit_array": {
      if (!value || !(value.bytes instanceof Uint8Array)) return false;
      const { bytes, bitLength } = value;
      return Number.isSafeInteger(bitLength) && bitLength >= 0 && bitLength <= 0xffffffff && bytes.length === Math.ceil(bitLength / 8);
    }
    case "externref": return true;
    default: return false;
  }
}

/** UTF-8, with a lone surrogate as its three bytes (WTF-8), which are not UTF-8. */
function utf8(text) {
  if (text.isWellFormed()) return encoder.encode(text);
  const bytes = [];
  for (const char of text) {
    const code = char.codePointAt(0);
    if (code >= 0xd800 && code <= 0xdfff) bytes.push(0xe0 | (code >> 12), 0x80 | ((code >> 6) & 0x3f), 0x80 | (code & 0x3f));
    else bytes.push(...encoder.encode(char));
  }
  return Uint8Array.from(bytes);
}

/** Reports whether this JavaScript value is a correct value of the type. */
function correct(type, value) {
  switch (type) {
    case "nil": return value === undefined || value === null;
    case "bool": return typeof value === "boolean";
    case "int": return typeof value === "bigint";
    case "float": return typeof value === "number" && Number.isFinite(value);
    // Lone surrogates are not Unicode scalar values.
    case "string": return typeof value === "string" && value.isWellFormed();
    case "bit_array": return correctBits(value);
    case "externref": return true;
    default: return false;
  }
}

/** A fault of the module: the instance is not used again. */
class ModuleFault extends AbiError {}

/** A value that the module gave and that is not correct. */
class GuestFault extends ModuleFault {
  constructor(message) {
    super(`The module gave a value that is not correct: ${message}`);
  }
}

class Bridge {
  resources;
  ending = false;
  instance;
  /** Whether an async export is waiting. */
  waiting = false;
  /** Why the instance cannot be used any more. */
  unusable = null;
  stopMessage = null;
  /** `{ error }` of a host function that threw, given to the caller after the module traps. */
  failure = null;
  /** Whether a host function failed or stopped the program; its guard then traps. */
  broken = false;
  /** Checks the answers of host functions in the host (`checkReplies`). */
  checkReplies = false;
  /** The outstanding requests by id: `{ namespace, label, signature, abort }`. */
  requests = new Map();
  /** Answers whose work is done, in the order they settled: `{ id, entry, outcome }` or `{ id, entry, failure }`. */
  settled = [];
  /** Resolves the wait for the next settled answer. */
  wake = null;
  /** Whether a request may start now: only during an async call, and not inside an import. */
  accepting = false;
  /** The Wasm calls of the host that are running. */
  depth = 0;

  exports() {
    if (!this.instance) throw new AbiError("Host memory access before instantiation");
    return this.instance.exports;
  }

  memory() {
    const memory = this.exports().memory;
    if (!(memory instanceof WebAssembly.Memory)) throw new AbiError("The module does not export memory");
    return memory;
  }

  copy(pointer, length) {
    const start = unsigned(pointer, "Address");
    const size = unsigned(length, "Length");
    if (!size) return new Uint8Array();
    const buffer = this.memory().buffer;
    if (start + size > buffer.byteLength) throw new GuestFault("a buffer outside memory");
    return new Uint8Array(buffer, start, size).slice();
  }

  /** A new buffer from ilang_alloc; an empty one has address 0. */
  allocate(bytes, owned) {
    if (!bytes.length) return 0;
    const allocator = this.exports().ilang_alloc;
    expect(typeof allocator === "function", "The module does not export ilang_alloc");
    const pointer = unsigned(this.guestCall(() => allocator(bytes.length)), "Allocation address");
    const buffer = this.memory().buffer;
    expect(pointer + bytes.length <= buffer.byteLength, "ilang_alloc gave a buffer outside memory");
    new Uint8Array(buffer, pointer, bytes.length).set(bytes);
    owned.push([pointer, bytes.length]);
    return pointer;
  }

  release(buffers) {
    if (!buffers.length) return;
    const free = this.exports().ilang_free;
    expect(typeof free === "function", "The module does not export ilang_free");
    const released = new Set();
    for (const [pointer, length] of buffers.toReversed()) {
      if (pointer === 0 || released.has(pointer)) continue;
      released.add(pointer);
      this.guestCall(() => free(pointer, length));
    }
  }

  usable() {
    expect(!this.unusable, `The instance cannot be used after it stopped (${this.unusable}); make a new instance`);
    expect(this.depth === 0, "The instance is running Wasm; a host function may not call it");
    expect(!this.waiting, "An async call is waiting; only its host functions may answer now");
    expect(!this.ending, "An invocation is tearing down; cleanup may not enter Wasm");
  }

  /**
   * An import callback that gets, first, whether a request could start when
   * the import was called. No request may start while it runs.
   */
  admitting(callback) {
    return (...raw) => {
      const admitted = this.accepting;
      this.accepting = false;
      try {
        return callback(admitted, ...raw);
      } finally {
        this.accepting = admitted;
      }
    };
  }

  /** Runs Wasm in which the module may start and cancel requests. */
  enterAccepting(operation) {
    return this.enter(() => {
      this.accepting = true;
      try {
        return operation();
      } finally {
        this.accepting = false;
      }
    });
  }

  /** Keeps the answer of a request, unless the request was dropped. */
  settle(id, entry, result) {
    if (this.requests.get(id) !== entry) return;
    this.settled.push({ id, entry, ...result });
    this.wake?.();
  }

  /** Drops every request: aborts its signal and forgets its answer. */
  dropRequests() {
    // The table is empty before any abort listener runs.
    const dropped = [...this.requests.values()];
    this.requests.clear();
    this.settled = [];
    for (const entry of dropped) { entry.detach(); entry.abort.abort(); }
  }

  /** The program stops with `host: value is not correct`. */
  hostValueStop() {
    this.endResources();
    this.dropRequests();
    this.unusable = HOST_VALUE_REASON;
    return new Stop(HOST_VALUE_REASON);
  }

  endResources(resources = this.resources) {
    const saved = this.ending;
    this.ending = true;
    try { return resources?.teardown(); }
    finally { this.ending = saved; }
  }

  liveContext() {
    if (!this.resources.live) {
      this.unusable ??= "The resource context has ended";
      throw new ModuleFault(this.unusable);
    }
  }

  /** Gates each actual guest call, including calls nested in argument lowering. */
  guestCall(operation) {
    this.liveContext();
    this.depth++;
    try {
      const result = operation();
      this.liveContext();
      return result;
    } finally { this.depth--; }
  }

  /** Translates a trap once at the enclosing SDK boundary. */
  enter(operation) {
    try { return this.guestCall(operation); }
    catch (error) { throw this.trapped(error); }
  }

  /**
   * In a host function: the program cannot go on, because the host function
   * threw (`failure` is `{ error }`) or its answer stops the program
   * (`failure` is null). Gives results of the right types; the guard of the
   * import then traps.
   */
  breakIn(signature, failure) {
    if (failure) this.failure ??= failure;
    else this.stopMessage ??= HOST_VALUE_REASON;
    this.broken = true;
    this.endResources();
    return signature.async ? [] : resultTypes(signature).map((wasm) => (wasm === 0x6f ? null : 0));
  }

  trapped(error) {
    this.endResources();
    this.dropRequests();
    if (this.failure) {
      const { error: failure } = this.failure;
      this.failure = null;
      this.stopMessage = null;
      this.unusable = String(failure?.message ?? failure);
      return failure instanceof ResourceError && failure.code === "memory exhausted" ? new Stop(null, { cause: failure }) : failure;
    }
    if (error instanceof ModuleFault) {
      this.unusable = error.message;
      return error;
    }
    const stop = new Stop(this.stopMessage, { cause: error });
    this.stopMessage = null;
    this.unusable = stop.message;
    return stop;
  }

  lower(type, value, owned) {
    switch (type) {
      case "nil": return [];
      case "bool": return [value ? 1 : 0];
      case "float": return [value];
      case "int": {
        const { sign, bytes } = integerToLimbs(value);
        return [sign, this.allocate(bytes, owned), bytes.length / 4];
      }
      case "string": {
        const bytes = utf8(value);
        return [this.allocate(bytes, owned), bytes.length];
      }
      case "bit_array": return [this.allocate(value.bytes, owned), value.bitLength];
      case "externref": return [value];
      default: throw new AbiError(`Unsupported ABI type ${type}`);
    }
  }

  /** Reads one value that the module gave, checking it. */
  lift(type, values, owned) {
    switch (type) {
      case "nil": return undefined;
      case "bool":
        if (values[0] !== 0 && values[0] !== 1) throw new GuestFault(`Bool ${values[0]}`);
        return values[0] === 1;
      case "float":
        if (typeof values[0] !== "number" || !Number.isFinite(values[0])) throw new GuestFault("a Float that is not finite");
        return values[0];
      case "externref": return values[0];
      case "string": {
        const [pointer, length] = values;
        const bytes = this.copy(pointer, length);
        if (owned && pointer) owned.push([unsigned(pointer, "Address"), bytes.length]);
        try { return decoder.decode(bytes); } catch { throw new GuestFault("a String that is not UTF-8"); }
      }
      case "int": {
        const [sign, pointer, count] = values;
        const bytes = this.copy(pointer, unsigned(count, "Count") * 4);
        if (owned && pointer) owned.push([unsigned(pointer, "Address"), bytes.length]);
        try { return integerFromLimbs(sign, bytes); } catch (error) { throw new GuestFault(error.message); }
      }
      case "bit_array": {
        const [pointer, rawBitLength] = values;
        const bitLength = unsigned(rawBitLength, "Bit length");
        const bytes = this.copy(pointer, Math.ceil(bitLength / 8));
        if (owned && pointer) owned.push([unsigned(pointer, "Address"), bytes.length]);
        if (!correctBits({ bytes, bitLength })) throw new GuestFault("a BitArray whose bits after the end are not 0");
        return { bytes, bitLength };
      }
      default: throw new AbiError(`Unsupported ABI type ${type}`);
    }
  }

  liftAll(types, values, owned) {
    const result = [];
    let offset = 0;
    for (const type of types) {
      const count = wasmTypes[type].length;
      result.push(this.lift(type, values.slice(offset, offset + count), owned));
      offset += count;
    }
    return result;
  }

  /** The results of an export: the value, or an GuestError for the tag. */
  liftResults(signature, values, owned) {
    if (!signature.errors.length) return { value: this.lift(signature.result, values, owned) };
    const tag = values[0];
    if (!Number.isInteger(tag) || tag < 0 || tag > signature.errors.length) throw new GuestFault(`error tag ${tag}`);
    let offset = 1;
    const types = [signature.result, ...signature.errors];
    for (let index = 0; index < types.length; index++) {
      const count = wasmTypes[types[index]].length;
      if (index === tag) {
        const value = this.lift(types[index], values.slice(offset, offset + count), owned);
        return tag === 0 ? { value } : { error: new GuestError(value) };
      }
      offset += count;
    }
  }

  /**
   * The answer of a host function as Wasm results, or null when the host
   * stops the program for it: when it is not of its type, or, with
   * `checkReplies`, not a correct value. Without `checkReplies`, a value of
   * the type that is not correct is given to the module, which checks it and
   * stops with the positions of the call. Successfully returned
   * buffers belong to the module.
   */
  lowerReply(signature, reply) {
    const fits = (type, value) => (this.checkReplies ? correct(type, value) : ofType(type, value));
    let tag = 0;
    let value = reply.value;
    if ("error" in reply) {
      value = reply.error;
      tag = signature.errors.findIndex((type) => fits(type, value) && kindOf(value) === type) + 1;
      if (!tag) return null;
    } else if (!fits(signature.result, value)) {
      return null;
    }
    const owned = [];
    try {
      const values = signature.errors.length ? [tag] : [];
      for (const [index, type] of [signature.result, ...signature.errors].entries()) {
        if (index === tag) values.push(...this.lower(type, value, owned));
        else values.push(...wasmTypes[type].map((wasm) => (wasm === 0x6f ? null : 0)));
      }
      return values;
    } catch (error) {
      try { this.release(owned); } catch { /* Keep the first error. */ }
      throw error;
    }
  }
}

/** The member of an error type that a JavaScript error value belongs to. */
function kindOf(value) {
  if (value === undefined || value === null) return "nil";
  if (typeof value === "boolean") return "bool";
  if (typeof value === "bigint") return "int";
  if (typeof value === "number") return "float";
  if (typeof value === "string") return "string";
  if (value && value.bytes instanceof Uint8Array) return "bit_array";
  return "externref";
}

function asArray(value, count) {
  if (count === 0) return [];
  if (count === 1) return [value];
  return value;
}

function importResult(values) {
  return values.length === 0 ? undefined : values.length === 1 ? values[0] : values;
}

async function compile(source) {
  if (source instanceof WebAssembly.Module) return source;
  if (typeof source === "string" || source instanceof URL || source instanceof Request) source = await fetch(source);
  if (source instanceof Response) {
    if (!source.ok) throw new AbiError(`Unable to fetch Wasm: HTTP ${source.status}`);
    source = await source.arrayBuffer();
  }
  try { return await WebAssembly.compile(source); } catch (cause) {
    throw new AbiError("Unable to compile the i module; the engine must support WasmGC, typed function references, tail calls and exnref", { cause });
  }
}

/** The answer of a host service function: its value, or the value of an GuestError it threw. */
function reply(fn, args) {
  try {
    return { value: fn(...args) };
  } catch (error) {
    if (error instanceof GuestError) return { error: error.value };
    throw error;
  }
}

// Authorization tokens are host objects. Neither JSON nor ABI fields can forge
// one, and each token is tied to the module compiled from its approved bytes.
const bindingAuthorizations = new WeakMap();

function validateBindingPlan(plan, abi) {
  expect(plan && typeof plan.artifact_digest === "string" && Array.isArray(plan.declarations), "Invalid binding plan");
  for (const declaration of plan.declarations) {
    for (const key of ["package", "module", "module_digest", "declaration", "namespace", "name"]) {
      expect(typeof declaration[key] === "string" && declaration[key].length > 0, "Binding plan has an empty declaration identity");
    }
    const table = declaration.kind === "service" ? abi.services : declaration.kind === "external" ? abi.externals : null;
    expect(table, "Binding plan has an invalid import kind");
    const signature = descriptor(declaration.signature, "binding declaration");
    expect(JSON.stringify(table[declaration.namespace]?.[declaration.name]) === JSON.stringify(signature),
      `Binding plan declaration ${declaration.declaration} does not match ABI import ${declaration.namespace} ${declaration.name}`);
  }
  for (const [kind, table] of [["service", abi.services], ["external", abi.externals]]) {
    for (const [namespace, fields] of Object.entries(table)) {
      for (const name of Object.keys(fields)) expect(plan.declarations.some((d) => d.kind === kind && d.namespace === namespace && d.name === name), `Binding plan is missing import ${namespace} ${name}`);
    }
  }
}

function freezePlan(value) {
  if (value && typeof value === "object") {
    for (const child of Object.values(value)) freezePlan(child);
    Object.freeze(value);
  }
  return value;
}

/**
 * Explicit embedding authority for a complete compiler plan, outside ABI v3.
 * The caller authenticates the plan's compiler/package provenance before
 * approving any declaration. A self-asserted manifest is not evidence.
 * Artifact bytes are required; a WebAssembly.Module cannot attest its bytes.
 */
export async function authorizeBindings(source, plan, approve, options = {}) {
  expect(typeof approve === "function", "Binding approval must be a function");
  expect(!(source instanceof WebAssembly.Module), "Binding authorization requires artifact bytes");
  if (typeof source === "string" || source instanceof URL || source instanceof Request) source = await fetch(source);
  if (source instanceof Response) {
    expect(source.ok, `Unable to fetch Wasm: HTTP ${source.status}`);
    source = await source.arrayBuffer();
  }
  const bytes = source instanceof ArrayBuffer ? new Uint8Array(source).slice()
    : ArrayBuffer.isView(source) ? new Uint8Array(source.buffer, source.byteOffset, source.byteLength).slice() : null;
  expect(bytes, "Binding authorization requires artifact bytes");
  const digest = new Uint8Array(await crypto.subtle.digest("SHA-256", bytes));
  const expected = "sha256-" + [...digest].map((b) => b.toString(16).padStart(2, "0")).join("");
  const snapshot = freezePlan(JSON.parse(JSON.stringify(plan)));
  expect(snapshot.artifact_digest === expected, "Binding plan artifact digest does not match the module");
  const module = await compile(bytes);
  const abi = readAbi(module, options.abi);
  validateBindingPlan(snapshot, abi);
  const approved = [];
  for (const declaration of snapshot.declarations) approved.push(await approve(declaration) === true);
  const token = Object.freeze({ module });
  bindingAuthorizations.set(token, { plan: snapshot, approved, abi });
  return token;
}

// Diagnostic names for host registration leaves; these grant no authority.
function providerRegistrations(module, abi) {
  const sections = WebAssembly.Module.customSections(module, "ilang.providers");
  expect(sections.length <= 1, "Duplicate ilang.providers sections");
  if (!sections.length) return [];
  let registrations;
  try { registrations = JSON.parse(decoder.decode(sections[0])); }
  catch (cause) { throw new AbiError("Malformed ilang.providers metadata", { cause }); }
  expect(Array.isArray(registrations), "ilang.providers must be an array");
  for (const registration of registrations) {
    plainObject(registration, "provider registration");
    only(registration, ["service", "namespace", "name"], "provider registration");
    for (const field of ["service", "namespace", "name"]) expect(typeof registration[field] === "string", `Provider registration needs ${field}`);
    expect(Object.hasOwn(abi.services[registration.namespace] ?? {}, registration.name), `Provider service ${registration.service} refers to an undeclared host function ${registration.namespace} ${registration.name}`);
  }
  return registrations;
}

function checkBindings(module, abi, options) {
  if (options.bindings) {
    const authorization = bindingAuthorizations.get(options.bindings);
    expect(authorization && options.bindings.module === module, "Binding authorization does not match the module");
    validateBindingPlan(authorization.plan, abi);
    for (const [index, d] of authorization.plan.declarations.entries()) {
      expect(authorization.approved[index] || typeof options.imports?.[d.namespace]?.[d.name] === "function",
        `ungranted host import ${d.namespace} ${d.name} declared by ${d.module} ${d.declaration}`);
    }
  } else {
    for (const table of [abi.services, abi.externals]) {
      for (const [namespace, fields] of Object.entries(table)) {
        for (const name of Object.keys(fields)) {
          expect(!options.contextImports?.[namespace]?.[name] || typeof options.imports?.[namespace]?.[name] === "function",
            `ungranted host import ${namespace} ${name}: a trusted binding plan or explicit declaration grant is required`);
        }
      }
    }
  }
}

/**
 * Loads a module, links its imports and calls `ilang_start` once.
 * `imports[module][name]` are the host service functions and external
 * functions of the metadata. They take and give ordinary JavaScript values; a
 * service function throws `GuestError(value)` to give an error of its `? E`,
 * and an async one gives a Promise.
 */
export async function instantiate(source, options = {}) {
  if (!supportsRequiredFeatures()) {
    throw new AbiError("This engine does not support WasmGC, typed function references, tail calls and exnref");
  }
  const module = await compile(source);
  const abi = readAbi(module, options.abi);
  const registrations = providerRegistrations(module, abi);
  const collections = readCollections(module);
  const standard = options.standardServices ? standardServices(options.standardServices === true ? {} : options.standardServices) : {};
  checkBindings(module, abi, options);
  const bridge = new Bridge();
  const resourceHost = options.resourceHost ?? defaultResourceHost;
  expect(resourceHost instanceof ResourceHost, "resourceHost must be a ResourceHost");
  bridge.resources = resourceHost.context();
  bridge.checkReplies = options.checkReplies ?? false;
  expect(typeof bridge.checkReplies === "boolean", "checkReplies must be a boolean");
  const imports = Object.create(null);
  const broken = typedFunction(() => (bridge.broken ? 1 : 0), [], [0x7f], `${namespace} guard`);
  const objectIds = new WeakMap();
  const primitiveIds = new Map();
  let nextReferenceId = 1n;
  for (const [name, values] of Object.entries(options.rawImports ?? {})) {
    expect(name !== namespace, `${namespace} imports are managed by the loader`);
    imports[name] = { ...values };
  }
  imports[namespace] = {
    // Drops an outstanding request.
    cancel: guardedFunction(bridge.admitting((admitted, id) => {
      const nothing = { result: "nil", errors: [] };
      if (bridge.broken) return importResult(bridge.breakIn(nothing, null));
      if (!admitted) return importResult(bridge.breakIn(nothing, { error: new ModuleFault(`the module cancelled request ${id} outside an async call`) }));
      const entry = bridge.requests.get(id);
      if (!entry) return importResult(bridge.breakIn(nothing, { error: new ModuleFault(`the module cancelled request ${id}, which is not outstanding`) }));
      bridge.requests.delete(id);
      bridge.settled = bridge.settled.filter((answer) => answer.entry !== entry);
      entry.detach();
      entry.abort.abort();
      return undefined;
    }), broken, [0x7f], [], `${namespace} cancel`),
    reference_id: guardedFunction(bridge.admitting((_, value) => {
      if (value === null) return 0n;
      const identities = (typeof value === "object" || typeof value === "function") ? objectIds : primitiveIds;
      let id = identities.get(value);
      if (id === undefined) {
        if (nextReferenceId > 0x7fffffffffffffffn) {
          bridge.breakIn({ result: "nil", errors: [] }, { error: new AbiError("Host reference identity space exhausted") });
          return 0n;
        }
        id = nextReferenceId++;
        identities.set(value, id);
      }
      return id;
    }), broken, [0x6f], [0x7e], `${namespace} reference_id`),
    // One worker in JavaScript: browser workers are not implemented, so
    // `i/task` never publishes a record (multicore D12).
    mc_publish: () => 0n,
    mc_claim: () => 1,
    mc_adopt: () => { throw new ModuleFault("mc_adopt without workers"); },
    mc_send: () => { throw new ModuleFault("mc_send without workers"); },
    mc_inbox: () => 0n,
    mc_message: () => { throw new ModuleFault("mc_message without workers"); },
    mc_pending: () => 0,
    mc_wait: () => undefined,
    mc_share_put: () => undefined,
    mc_share_get: () => 0n,
    mc_share_drop: () => undefined,
    // The module traps right after this call.
    panic: typedFunction(bridge.admitting((_, pointer, length) => {
      let message;
      try {
        message = lossy.decode(bridge.copy(pointer, length));
      } catch (error) {
        message = `(the stop message is outside memory: ${error.message})`;
      }
      bridge.stopMessage ??= message;
      bridge.endResources();
    }), [0x7f, 0x7f], [], `${namespace} panic`),
  };
  for (const [kind, table] of [["service", abi.services], ["external", abi.externals]]) {
    for (const [moduleName, entries] of Object.entries(table)) {
      imports[moduleName] ??= Object.create(null);
      for (const [name, signature] of Object.entries(entries)) {
        const legacy = options.imports?.[moduleName]?.[name];
        const contextFn = options.contextImports?.[moduleName]?.[name] ?? (!legacy ? standard[moduleName]?.[name] : undefined);
        expect(!(legacy && contextFn), `Host function ${moduleName} ${name} is registered twice`);
        const services = registrations.filter((d) => d.namespace === moduleName && d.name === name).map((d) => d.service);
        const service = services.length ? ` for service ${services.join(", ")}` : "";
        expect(typeof (contextFn ?? legacy) === "function", `Missing host function ${moduleName} ${name}${service}`);
        expect(!Object.hasOwn(imports[moduleName], name), `Host function ${moduleName} ${name} is registered twice`);
        // Nothing is thrown into the module: an exception of the
        // host function, or an answer that stops the program, is kept, and
        // the guard of the import traps.
        const callback = (admitted, ...raw) => {
          if (bridge.broken) return importResult(bridge.breakIn(signature, null));
          const resources = bridge.resources;
          if (!resources.live) return importResult(bridge.breakIn(signature, { error: new AbiError("The resource context has ended") }));
          const fn = contextFn ? (...args) => contextFn(resources, ...args) : legacy;
          // An async import takes the request id first, which is checked
          // before the service runs.
          const id = signature.async ? raw.shift() : undefined;
          if (signature.async) {
            const refused = !admitted ? `the module started request ${id} outside an async call`
              : id < 0 ? `the module started request ${id}, which is below 0`
                : bridge.requests.has(id) ? `the module started request ${id} twice` : null;
            if (refused) return importResult(bridge.breakIn(signature, { error: new ModuleFault(refused) }));
          }
          try {
            const args = bridge.liftAll(signature.params, raw);
            if (signature.async) {
              // The service runs now, during the import, with the signal of
              // this request.
              const abort = resources.abortController();
              const target = new WeakRef(bridge);
              const detach = resources.ownRequest(() => { abort.abort(); target.deref()?.wake?.(); });
              const saved = currentSignal;
              currentSignal = abort.signal;
              let started;
              try {
                started = Promise.resolve(fn(...args));
              } catch (error) {
                started = Promise.reject(error);
              } finally {
                currentSignal = saved;
              }
              const work = started.then((value) => ({ value }), (error) => {
                if (error instanceof GuestError) return { error: error.value };
                throw error;
              });
              const entry = { namespace: moduleName, label: name, signature, abort, detach };
              bridge.requests.set(id, entry);
              // An unresolved Promise must not retain the Wasm instance after
              // disposal. Each reply still checks the original request entry.
              work.then((outcome) => target.deref()?.settle(id, entry, { outcome }), (failure) => target.deref()?.settle(id, entry, { failure }));
              // A started request requires its resume even if the module
              // cancels it or returns status 0 next.
              const resume = `ilang_resume:${moduleName}:${name}`;
              try {
                validateFunction(module, bridge.instance.exports, resume, [0x7f, ...resultTypes(signature)], [0x7f]);
              } catch {
                return importResult(bridge.breakIn(signature, { error: new ModuleFault(`the module does not export ${resume}`) }));
              }
              return undefined;
            }
            const answer = kind === "service" ? reply(fn, args) : { value: fn(...args) };
            bridge.liveContext();
            expect(signature.result === "externref" || !answer.value || typeof answer.value.then !== "function", `${moduleName} ${name} is not async; it must not give a Promise`);
            const values = bridge.lowerReply(signature, answer);
            return importResult(values ?? bridge.breakIn(signature, null));
          } catch (error) {
            return importResult(bridge.breakIn(signature, { error }));
          }
        };
        const params = signature.async ? [0x7f, ...paramTypes(signature)] : paramTypes(signature);
        imports[moduleName][name] = guardedFunction(bridge.admitting(callback), broken, params, signature.async ? [] : resultTypes(signature), `${moduleName} ${name}`);
      }
    }
  }
  const instance = await WebAssembly.instantiate(module, imports);
  bridge.instance = instance;
  for (const [name, signature] of Object.entries(abi.exports)) {
    validateFunction(module, instance.exports, name, paramTypes(signature), signature.async ? [0x7f] : resultTypes(signature));
  }
  for (const point of [...(abi.entry ? [abi.entry] : []), ...abi.tests]) {
    validateFunction(module, instance.exports, point.name, [], point.async ? [0x7f] : []);
  }
  for (const [name, params, results] of [
    ["ilang_alloc", [0x7f], [0x7f]],
    ["ilang_free", [0x7f, 0x7f], []],
  ]) if (instance.exports[name] !== undefined) validateFunction(module, instance.exports, name, params, results);
  validateFunction(module, instance.exports, "ilang_start", [], []);
  bridge.enter(() => instance.exports.ilang_start());

  const signatureOf = (name, args) => {
    const signature = abi.exports[name];
    expect(signature, `No ABI descriptor for exported function ${name}`);
    expect(Array.isArray(args) && args.length === signature.params.length, `${name} expects ${signature.params.length} arguments`);
    return signature;
  };

  /** The export `name` with these Wasm types, or a fault of the module. */
  const exportOrFault = (name, params, results, text) => {
    try {
      validateFunction(module, instance.exports, name, params, results);
    } catch {
      throw bridge.trapped(new ModuleFault(text));
    }
  };

  /**
   * Answers the requests of the module, in the order their work settles,
   * until the status is 0. Every exit drops the requests that are left.
   */
  const wait = async (name, status) => {
    bridge.waiting = true;
    try {
      bridge.liveContext();
      while (status !== 0) {
        bridge.liveContext();
        let next;
        if (status === 1) {
          if (!bridge.requests.size) throw bridge.trapped(new ModuleFault("the module waits, but no host function is running"));
          while (!bridge.settled.length) {
            if (bridge.unusable) throw new AbiError(`The instance cannot be used (${bridge.unusable})`);
            if (!bridge.resources.live) throw bridge.trapped(new ModuleFault("The resource context has ended"));
            await new Promise((resolve) => (bridge.wake = resolve));
          }
          bridge.wake = null;
          next = bridge.settled.shift();
        } else if (status === 2) {
          exportOrFault("ilang_continue", [], [0x7f], "the module is runnable, but has no ilang_continue");
          // Let timers and IO run once, then give an answer that is done,
          // or go on without one.
          await macrotask();
          bridge.liveContext();
          next = bridge.settled.shift();
          if (!next) {
            status = bridge.enterAccepting(() => instance.exports.ilang_continue());
            continue;
          }
        } else {
          throw bridge.trapped(new ModuleFault(`export ${name} gave the status ${status}, which is not 0, 1 or 2`));
        }
        const { id, entry } = next;
        if (!bridge.resources.live) throw bridge.trapped(new ModuleFault("The resource context has ended"));
        bridge.requests.delete(id);
        entry.detach();
        if ("failure" in next) {
          bridge.unusable = String(next.failure?.message ?? next.failure);
          if (next.failure instanceof ResourceError && next.failure.code === "memory exhausted") throw new Stop(null, { cause: next.failure });
          throw next.failure;
        }
        const resume = `ilang_resume:${entry.namespace}:${entry.label}`;
        exportOrFault(resume, [0x7f, ...resultTypes(entry.signature)], [0x7f], `the module does not export ${resume}`);
        // Result buffers are made just before the resume.
        const values = bridge.enter(() => bridge.lowerReply(entry.signature, next.outcome));
        if (!values) throw bridge.hostValueStop();
        status = bridge.enterAccepting(() => instance.exports[resume](id, ...values));
      }
    } finally {
      // The abort listeners of the dropped requests run during the drop.
      // The instance still waits then, so they cannot start a call on it.
      bridge.dropRequests();
      bridge.waiting = false;
    }
  };

  const finish = (signature, raw, owned) => {
    const values = asArray(raw, resultTypes(signature).length);
    let result;
    try {
      result = bridge.liftResults(signature, values, owned);
      bridge.release(owned);
    } catch (error) {
      throw bridge.trapped(error);
    }
    if (result.error) throw result.error;
    return result.value;
  };

  const runPoint = (point) => {
    bridge.usable();
    if (!point.async) {
      bridge.enter(() => instance.exports[point.name]());
      return undefined;
    }
    return (async () => {
      const status = bridge.enterAccepting(() => instance.exports[point.name]());
      await wait(point.name, status);
      const result = `ilang_result:${point.name}`;
      validateFunction(module, instance.exports, result, [], []);
      bridge.enter(() => instance.exports[result]());
    })();
  };

  const guest = {
    module, instance, exports: instance.exports, abi, collections,
    /** Why the instance cannot be used any more, or null. */
    get unusable() { return bridge.unusable; },
    /**
     * Calls a host export. Gives its value, throws GuestError for an error of
     * its `? E`, and Stop when the program stops. Arguments that are not
     * correct values stop the program with `host: value is not correct`.
     */
    call(name, args = []) {
      bridge.usable();
      const signature = signatureOf(name, args);
      expect(!signature.async, `${name} is async; use callAsync`);
      if (!signature.params.every((type, index) => correct(type, args[index]))) throw bridge.hostValueStop();
      const owned = [];
      const raw = bridge.enter(() => {
        const rawArguments = signature.params.flatMap((type, index) => bridge.lower(type, args[index], owned));
        return bridge.guestCall(() => instance.exports[name](...rawArguments));
      });
      return finish(signature, raw, owned);
    },
    /** Calls an async host export; the Promise settles like `call`. */
    async callAsync(name, args = []) {
      bridge.usable();
      const signature = signatureOf(name, args);
      expect(signature.async, `${name} is not async; use call`);
      if (!signature.params.every((type, index) => correct(type, args[index]))) throw bridge.hostValueStop();
      const owned = [];
      const status = bridge.enter(() => {
        const rawArguments = signature.params.flatMap((type, index) => bridge.lower(type, args[index], owned));
        bridge.accepting = true;
        try {
          return bridge.guestCall(() => instance.exports[name](...rawArguments));
        } finally {
          bridge.accepting = false;
        }
      });
      await wait(name, status);
      const result = `ilang_result:${name}`;
      validateFunction(module, instance.exports, result, [], resultTypes(signature));
      const raw = bridge.enter(() => instance.exports[result]());
      return finish(signature, raw, owned);
    },
    /** Runs the program entry; a Promise when it is async. */
    run() {
      expect(abi.entry, "The program has no entry");
      return runPoint(abi.entry);
    },
    /** Runs an entry point by name: the program entry or a test. */
    runEntryPoint(name) {
      const point = [...(abi.entry ? [abi.entry] : []), ...abi.tests].find((candidate) => candidate.name === name);
      expect(point, `${name} is not an entry point of the metadata`);
      return runPoint(point);
    },
    /** Runs the selected contribution in this artifact. */
    runCollection(handle) {
      expect(collections && collections.selected === handle, "The collection handle is not selected by this artifact");
      validateFunction(module, instance.exports, collections.export, [], collections.is_async ? [0x7f] : []);
      return runPoint({ name: collections.export, async: collections.is_async });
    },
    /** Abandons a live invocation and cleans up host resources without i callbacks. */
    takeCleanupErrors() { return resourceHost.takeCleanupErrors(); },
    dispose() {
      bridge.unusable ??= "the instance was disposed";
      bridge.endResources();
      bridge.dropRequests();
      bridge.wake?.();
    },
  };
  // All invocation paths share the same ownership boundary. The immutable
  // captured context also survives Promise callbacks after disposal.
  for (const name of ["call", "callAsync", "run", "runEntryPoint", "runCollection"]) {
    const operation = guest[name];
    const invoke = (...args) => {
      bridge.usable();
      bridge.endResources();
      const resources = resourceHost.context();
      bridge.resources = resources;
      try {
        const value = operation(...args);
        const asynchronous = name === "callAsync" || (name === "run" && abi.entry?.async)
          || (name === "runEntryPoint" && [...(abi.entry ? [abi.entry] : []), ...abi.tests].find((point) => point.name === args[0])?.async)
          || (name === "runCollection" && collections?.is_async);
        if (asynchronous) return value.finally(() => bridge.endResources(resources));
        bridge.endResources(resources);
        return value;
      } catch (error) {
        bridge.endResources(resources);
        throw error;
      }
    };
    guest[name] = name === "callAsync" ? async (...args) => invoke(...args) : invoke;
  }
  return Object.freeze(guest);
}

/** Runs each test in a new instance; a stop fails only its own test. */
export async function runTests(source, options = {}) {
  const module = await compile(source);
  const abi = readAbi(module, options.abi);
  const names = options.tests ?? abi.tests.map((test) => test.name);
  const results = [];
  for (const name of names) {
    try {
      const guest = await instantiate(module, options);
      await guest.runEntryPoint(name);
      results.push({ name, passed: true });
    } catch (error) {
      results.push({ name, passed: false, error });
    }
  }
  return results;
}
