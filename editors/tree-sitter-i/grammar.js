// Syntax three (docs/design/syntax-3.md §3; docs/spec.md §§1–8 for what it
// keeps). Following tree-sitter-gleam, postfix operations are recursive
// alternatives and operators have explicit left precedence.
const list = (item, sep) => optional(seq(item, repeat(seq(sep, item)), optional(sep)));
module.exports = grammar({
  name: 'i',
  externals: $ => [$._break, $.string_start, $.string_content, $.string_end, $.escape_sequence, $.interpolation_start, $.interpolation_end],
  extras: $ => [/\s/, $.module_comment, $.doc_comment, $.comment],
  word: $ => $.identifier,
  conflicts: $ => [
    [$._atom, $.data_pattern_item, $.type_item],
    [$.data_pattern, $.data_type],
    [$.export, $.rest_pattern],
    [$.parameter, $._atom],
    [$.exports, $.parameters],
    [$._atom, $._type],
    [$._atom, $.data_pattern_item],
    [$._atom, $.value_type],
    [$.type_head, $.data_pattern],
    [$.data_item, $.parameter, $._atom],
    [$._expression, $.rest_pattern],
    [$.import, $._expression, $.constructor_pattern],
    [$.data_item, $.parameter, $._atom, $.data_pattern_item],
    [$.import, $.data_pattern],
    [$._choices, $.data_pattern_item],
    [$.import, $.data_item, $.parameter, $._atom, $.data_pattern_item],
    [$.export, $._expression, $._atom],
    [$.imports, $.exports, $.parameters],
    [$.imports, $.exports],
    [$.imports, $.exports, $.data],
    [$.exports, $.data],
    [$.import, $._expression],
    [$.import, $._expression, $._atom],
    [$.import, $._atom],
    [$.export, $._expression],
    [$.export, $._expression, $.constructor_pattern],
    [$.export, $.constructor_pattern],
    [$._expression, $._atom],
    [$._expression, $.constructor_pattern],
    [$._expression, $._atom, $.constructor_pattern],
    [$._atom, $.constructor_pattern],
    [$._expression, $.data_item, $._atom],
    [$.data_item, $._atom],
    [$.data, $.data_pattern],
    [$.data, $.parameters],
    [$.data, $.data_pattern, $.parameters],
    [$.data_pattern, $.parameters],
    [$.data_item, $.data_pattern_item],
    [$.data_item, $.data_pattern_item, $.parameter],
    [$.data_pattern_item, $.parameter],
    [$._pattern, $.parameter],
    [$._pattern, $.data_pattern_item],
    [$._pattern, $.data_pattern_item, $.parameter],
    [$.spread, $.rest_pattern],
    [$.list, $.list_pattern],
    [$.bit_array, $.bit_pattern],
    [$._expression, $.negative_pattern],
    [$._expression, $.prefix_pattern],
    [$._expression, $._segment_pattern],
    [$._expression, $.constructor_pattern, $._segment_pattern],
    [$.constructor_pattern, $._segment_pattern],
    [$._item, $._expression],
    [$.binding, $._expression],
    [$.declaration, $._atom],
    [$.typed_pattern, $._atom],
    [$.named_type],
    [$.value_type, $.type_call],
    [$.data_type, $.function_type],
    [$.type_group, $.function_type],
    [$.branches],
    [$.function],
    [$.type_head, $.data_type],
    [$.data_type],
    [$.type_item, $.value_type],
    [$.type_item, $.value_type, $.type_call],
    [$._pattern],
    [$.attribute],
    [$.module_path, $._expression],
  ],
  rules: {
    source_file: $ => seq(optional(seq($.imports, optional($._break))), optional(seq($.exports, optional($._break))), repeat(seq($._item, optional($._break)))),
    _separator: $ => choice(',', $._break),
    imports: $ => seq('(', list($.import, $._separator), ')'),
    import: $ => seq(optional(seq(field('alias', $.identifier), '=')), optional(seq('(', list(choice($.identifier, $.type_identifier), $._separator), ')', '=')), $.module_path),
    module_path: $ => seq($.identifier, repeat1(seq('/', $.identifier))),
    exports: $ => seq('(', list($.export, $._separator), ')'),
    export: $ => choice($.identifier, seq($.type_identifier, optional(seq('(', '..', ')')))),
    _item: $ => choice($.attribute, $.type_definition, $.binding, $.declaration, $.call),
    attribute: $ => seq('@', optional(seq($.identifier, '.')), field('name', $.identifier), optional($.data)),
    // `T(A) = type`; `T = Opaque` is a named type.
    type_definition: $ => prec(20, seq(field('name', $.type_identifier), optional($.type_head), '=', $._type)),
    type_head: $ => seq('(', list($._type, $._separator), ')'),
    binding: $ => prec.right(seq(field('pattern', $._atom), repeat(seq('=', $._atom)), '=', field('value', $._expression))),
    declaration: $ => seq(field('name', $.identifier), ':', $._annot),

    // ---- Expressions (§3.3) ----
    _expression: $ => choice($.identifier, $.type_identifier, $.integer, $.float, $.string, $.data, $.list, $.bit_array,
      $.block, $.function, $.branches, $.call, $.field_access, $.binary_expression, $.unary_expression, $.pipe, $.provide),
    // `e <- s`: the weakest level, left associative; `s` is one postfix operand.
    provide: $ => prec.left(0, seq(field('target', $._expression), '<-', field('services', $._expression))),
    pipe: $ => prec.left(1, seq(field('left', $._expression), '|>', field('right', $._expression))),
    unary_expression: $ => prec(11, seq(choice('-', '-.'), $._expression)),
    binary_expression: $ => choice(...[
      [2, ['||']], [3, ['&&']], [4, ['==', '!=']],
      [5, ['<', '<=', '>', '>=', '<.', '<=.', '>.', '>=.']],
      [6, ['<>']], [7, ['+', '-', '+.', '-.']], [8, ['*', '/', '%', '*.', '/.']],
    ].map(([p, ops]) => prec.left(p, seq(field('left', $._expression), field('operator', ops.length === 1 ? ops[0] : choice(...ops)), field('right', $._expression))))),
    call: $ => prec.left(12, seq(field('function', $._expression), field('arguments', $.data))),
    field_access: $ => prec.left(12, seq(field('value', $._expression), '.', field('field', choice($.identifier, alias(/[0-9][0-9_]*/, $.integer), $.type_identifier)))),
    // `( items )`: data, the argument of a call, and the provided services.
    data: $ => seq('(', list(choice($.data_item, $.spread), $._separator), ')'),
    data_item: $ => choice(seq(field('label', $.identifier), '=', field('value', $._expression)), $._expression),
    spread: $ => seq('..', optional($._expression)),
    list: $ => seq('[', list(choice($._expression, $.spread), $._separator), ']'),
    bit_array: $ => seq('<<', list($.bit_segment, $._separator), '>>'),
    bit_segment: $ => seq($._expression, optional(seq(':', $.bit_format))),
    bit_format: $ => seq($.identifier, optional(seq('(', $._expression, ')'))),
    block: $ => seq('{', repeat(seq($._statement, optional($._break))), '}'),
    _statement: $ => choice($.binding, $._expression),
    // `F1 | F2 | …` (§2.5); a match is `e |> F1 | F2`.
    branches: $ => prec.left(seq($.function, repeat1(seq('|', $.function)))),
    function: $ => prec.right(seq(optional($.type_parameters), $.parameters, optional($.service_pattern), optional($.return_type), field('body', $.block))),
    type_parameters: $ => seq('<', list($.type_identifier, ','), '>'),
    parameters: $ => seq('(', list($.parameter, $._separator), optional($.guard), ')'),
    parameter: $ => choice(seq(field('key', $.identifier), '=', $._choices), $._choices),
    _choices: $ => seq($._pattern, repeat(seq('|', $._pattern))),
    guard: $ => seq('?', $._expression),
    service_pattern: $ => seq('<-', '(', list($.service_item, $._separator), ')'),
    service_item: $ => choice(seq($.identifier, ':', $.named_type), seq('..', $.identifier, ':', $.type_identifier)),
    return_type: $ => seq('->', $._type),

    // ---- Patterns (§3.4) ----
    _pattern: $ => prec.right(choice($._atom, $.alias_pattern)),
    alias_pattern: $ => prec.right(seq($._atom, '=', $._pattern)),
    _atom: $ => choice($.identifier, $.discard, $.typed_pattern, $.integer, $.float, $.string, $.negative_pattern,
      $.constructor_pattern, $.data_pattern, $.list_pattern, $.bit_pattern, $.prefix_pattern),
    typed_pattern: $ => prec.right(2, seq(field('pattern', choice($.identifier, $.discard)), ':', $._annot)),
    negative_pattern: $ => choice(seq('-', $.integer), seq('-.', $.float)),
    constructor_pattern: $ => prec.right(0, seq(optional(seq($.identifier, '.')), $.type_identifier, optional($.data_pattern))),
    data_pattern: $ => seq('(', list(choice($.data_pattern_item, $.rest_pattern), $._separator), ')'),
    data_pattern_item: $ => choice(seq(field('key', $.identifier), '=', $._pattern), $._pattern),
    list_pattern: $ => seq('[', list(choice($._pattern, $.rest_pattern), $._separator), ']'),
    rest_pattern: $ => seq('..', optional(choice($.identifier, $.discard))),
    bit_pattern: $ => seq('<<', list($.pattern_segment, $._separator), '>>'),
    pattern_segment: $ => seq($._segment_pattern, optional(seq(':', $.bit_format))),
    _segment_pattern: $ => choice($.identifier, $.discard, $.type_identifier, $.integer, $.float, $.string, $.negative_pattern, $.constructor_pattern, $.list_pattern, $.bit_pattern, $.prefix_pattern),
    prefix_pattern: $ => choice(
      seq($.string, '<>', choice($.identifier, $.discard), optional(seq('<>', $.string))),
      seq(choice($.identifier, $.discard), '<>', $.string)),

    // ---- Types (§3.1) ----
    _type: $ => choice($.named_type, $.value_type, $.type_call, $.integer, $.string, $.discard, $.negative_type,
      $.data_type, $.type_group, $.function_type, $.binary_type),
    // Annot = Inter: only brackets admit a union; an unbracketed function
    // result keeps that same boundary. Aliases preserve the editor node API.
    _annot: $ => choice($.named_type, $.value_type, $.type_call, $.integer, $.string, $.discard, $.negative_type,
      $.data_type, $.type_group, alias($._annot_function, $.function_type), alias($._annot_binary, $.binary_type)),
    _annot_binary: $ => choice(...[[2, '&'], [3, '-']].map(([p, op]) => prec.left(p, seq($._annot, op, $._annot)))),
    _annot_function: $ => prec.right(seq(optional($.type_parameters), choice($.data_type, $.type_group), optional(seq('<-', $.needs)), '->', $._annot)),
    named_type: $ => prec(11, seq(optional(seq($.identifier, '.')), $.type_identifier, optional($.type_arguments))),
    value_type: $ => seq(optional(seq($.identifier, '.')), $.identifier),
    type_call: $ => seq(optional(seq($.identifier, '.')), $.identifier, $.type_arguments),
    type_arguments: $ => seq('(', $._type, repeat(seq($._separator, $._type)), optional($._separator), ')'),
    negative_type: $ => prec(4, seq('-', choice($.integer, $.type_group))),
    binary_type: $ => choice(...[[1, '|'], [2, '&'], [3, '-']].map(([p, op]) => prec.left(p, seq($._type, op, $._type)))),
    data_type: $ => seq('(', list($.type_item, $._separator), ')'),
    type_item: $ => choice(seq(field('label', $.identifier), '=', $._type), $._type),
    type_group: $ => seq('{', $._type, '}'),
    // `<A>(P) <- (S, ..N) -> R`.
    function_type: $ => prec.right(seq(optional($.type_parameters), choice($.data_type, $.type_group), optional(seq('<-', $.needs)), '->', $._type)),
    needs: $ => choice($.type_identifier, seq('(', list(choice($.named_type, seq('..', $.type_identifier)), $._separator), ')')),

    identifier: _ => /_?[a-z][a-z0-9_]*/,
    type_identifier: _ => /[A-Z][A-Za-z0-9]*/,
    discard: _ => /_|__[a-z0-9_]*/,
    integer: _ => /0x[0-9a-fA-F][0-9a-fA-F_]*|0o[0-7][0-7_]*|0b[01][01_]*|[0-9][0-9_]*/,
    float: _ => /[0-9][0-9_]*\.[0-9_]*(e-?[0-9][0-9_]*)?/,
    string: $ => seq($.string_start, repeat(choice($.string_content, $.escape_sequence, $.interpolation)), $.string_end),
    interpolation: $ => seq($.interpolation_start, $._expression, $.interpolation_end),
    module_comment: _ => token(prec(3, /\/\/\/\/[^\r\n]*/)),
    doc_comment: _ => token(prec(2, /\/\/\/[^\r\n]*/)),
    comment: _ => token(prec(1, /\/\/[^\r\n]*/)),
  }
});
