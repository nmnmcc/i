// docs/spec.md §§1–8. Following tree-sitter-gleam, postfix operations are
// recursive alternatives and operators have explicit left precedence.
const list = (item, sep) => optional(seq(item, repeat(seq(sep, item)), optional(sep)));
module.exports = grammar({
  name: 'i',
  externals: $ => [$._break, $.string_content],
  extras: $ => [/\s/, $.module_comment, $.doc_comment, $.comment],
  word: $ => $.identifier,
  conflicts: $ => [
    [$.constructor_pattern, $._segment_pattern],
    [$._expression, $.constructor_pattern, $._segment_pattern],
    [$._expression, $._segment_pattern],
    [$.exports, $.record],
    [$.record, $.tuple_pattern],
    [$.imports, $.exports, $.record],
    [$.export, $.constructor_pattern],
    [$.import, $._pattern, $.constructor_pattern],
    [$._pattern, $.constructor_pattern, $.type_field],
    [$.constructor_pattern, $.type_arguments],
    [$.import, $._expression, $._pattern, $.constructor_pattern],
    [$._expression, $._pattern, $.constructor_pattern],
    [$.export, $._expression, $.constructor_pattern],
    [$.export, $._expression, $._pattern, $.constructor_pattern],
    [$._pattern, $.constructor_pattern],
    [$._expression, $.constructor_pattern],
    [$._pattern, $.alias_pattern],
    [$.type_parameter, $.type_field],
    [$.return_type],
    [$.import, $._pattern],
    [$._pattern, $.type_field],
    [$._pattern, $.type_parameter, $.type_field],
    [$.tuple_pattern, $.type_tuple],
    [$.type_tuple, $.type_parameter],
    [$.exports, $.parameters],
    [$._pattern, $.value_type],
    [$.named_type],
    [$.value_type, $.type_call],
    [$._expression, $.rest_pattern],
    [$.bit_array, $.bit_pattern],
    [$.list, $.list_pattern],
    [$._expression, $.negative_pattern],
    [$.import, $._expression, $._pattern],
    [$.spread, $.rest_pattern],
    [$.binding, $._expression],
    [$.record, $.block, $.clause_block],
    [$.attribute],
    [$.record_field, $._pattern],
    [$.module_path, $._expression],
    [$.export, $._expression, $._pattern],
    [$.imports, $.exports, $.parameters],
    [$.imports, $.exports],
    [$._expression, $.prefix_pattern],
    [$._item, $._expression],
    [$.declaration, $._pattern],
    [$.binding, $.declaration, $._expression],
    [$._expression, $._pattern],
    [$._type, $._pattern],
    [$.tuple_pattern, $.parameters],
    [$.record, $.parameters],
    [$.type_tuple, $.type_parameters_list],
  ],
  rules: {
    source_file: $ => seq(optional(seq($.imports, optional($._break))), optional(seq($.exports, optional($._break))), repeat(seq($._item, optional($._break)))),
    _separator: $ => choice(',', $._break),
    imports: $ => seq('(', list($.import, $._separator), ')'),
    import: $ => seq(optional(seq(field('alias', $.identifier), '=')), optional(seq('(', list(choice($.identifier, $.type_identifier), $._separator), ')', '=')), $.module_path),
    module_path: $ => seq($.identifier, repeat1(seq('/', $.identifier))),
    exports: $ => seq('(', list($.export, $._separator), ')'),
    export: $ => choice($.identifier, seq($.type_identifier, optional(seq('(', '..', ')')))),
    _item: $ => choice($.attribute, $.type_definition, $.binding, $.declaration, $.call),
    attribute: $ => seq('@', optional(seq($.identifier, '.')), field('name', $.identifier), optional($.arguments)),
    type_definition: $ => prec(20, seq(field('name', $.type_identifier), optional($.type_arguments), choice(seq('=', $._type), seq('{', repeat(seq($.constructor, optional($._break))), '}')))),
    constructor: $ => seq(field('name', $.type_identifier), optional($.type_parameters_list)),
    type_parameters: $ => seq('(', list($.type_identifier, $._separator), ')'),
    binding: $ => prec.right(seq(field('pattern', choice($._pattern, seq($.identifier, $.type_parameters, optional(seq(':', $._type))))), '=', field('value', $._expression))),
    declaration: $ => seq(field('name', $.identifier), optional($.type_parameters), ':', $._type),
    _expression: $ => choice($.identifier, $.type_identifier, $.integer, $.float, $.string, $.tuple, $.record, $.list, $.bit_array, $.block, $.clause_block, $.function, $.call, $.field_access, $.binary_expression, $.unary_expression),
    unary_expression: $ => prec(10, seq(choice('-', '-.'), $._expression)),
    binary_expression: $ => choice(...[
      [1, ['||']], [2, ['&&']], [3, ['==', '!=']],
      [4, ['<', '<=', '>', '>=', '<.', '<=.', '>.', '>=.']],
      [5, ['<>']], [6, ['|>']], [7, ['+', '-', '+.', '-.']], [8, ['*', '/', '%', '*.', '/.']],
    ].map(([p, ops]) => prec.left(p, seq(field('left', $._expression), field('operator', ops.length === 1 ? ops[0] : choice(...ops)), field('right', $._expression))))),
    call: $ => prec.left(12, seq(field('function', $._expression), $.arguments)),
    arguments: $ => seq('(', list(choice($.argument, $.spread), $._separator), ')'),
    argument: $ => seq(optional(seq(field('label', $.identifier), ':')), $._expression),
    spread: $ => seq('..', optional($._expression)),
    field_access: $ => prec.left(12, seq(field('value', $._expression), '.', field('field', choice($.identifier, alias(/[0-9][0-9_]*/, $.integer), $.type_identifier)))),
    tuple: $ => seq('(', $._expression, repeat(seq($._separator, $._expression)), optional($._separator), ')'),
    record: $ => choice(seq('(', optional($._record_fields), ')'), seq('{', optional($._record_fields), '}')),
    _record_fields: $ => choice(seq($.record_field, repeat(seq($._separator, $.record_field)), optional($._separator)), seq($.spread, repeat(seq($._separator, $.record_field)), optional($._separator))),
    record_field: $ => seq(field('label', choice($.identifier, $.string)), ':', field('value', $._expression)),
    list: $ => seq('[', list(choice($._expression, $.spread), $._separator), ']'),
    bit_array: $ => seq('<<', list($.bit_segment, $._separator), '>>'),
    bit_segment: $ => seq($._expression, optional(seq(':', $.bit_format))),
    bit_format: $ => seq($.identifier, optional(seq('(', $._expression, ')'))),
    function: $ => prec.right(seq($.parameters, optional($.return_type), field('body', $.block))),
    parameters: $ => seq('(', list(choice($._pattern, $.environment_parameter), $._separator), ')'),
    environment_parameter: $ => seq($.identifier, '!', $.named_type),
    return_type: $ => seq('->', $._type, optional($.error_type), optional($.service_row)),
    error_type: $ => seq(choice('^', '?'), $._type),
    service_row: $ => seq('!', $._type),
    block: $ => seq('{', repeat(seq($._statement, optional($._break))), '}'),
    _statement: $ => choice($.binding, $.environment_statement, $._expression),
    environment_statement: $ => seq('!', $.named_type, '=', $._expression),
    clause_block: $ => prec.dynamic(1, seq('{', repeat(seq($.clause, optional($._break))), '}')),
    clause: $ => seq($._pattern, repeat(seq('|', $._pattern)), optional($.guard), '->', $._expression),
    guard: $ => seq('?', $._expression),
    _pattern: $ => choice($.identifier, $.discard, $.type_identifier, $.integer, $.float, $.string, $.negative_pattern, $.constructor_pattern, $.tuple_pattern, $.list_pattern, $.bit_pattern, $.typed_pattern, $.alias_pattern, $.prefix_pattern),
    negative_pattern: $ => choice(seq('-', $.integer), seq('-.', $.float)),
    constructor_pattern: $ => prec.right(0, seq(optional(seq($.identifier, '.')), $.type_identifier, optional(seq('(', list(choice($._pattern, '..'), $._separator), ')')))),
    tuple_pattern: $ => seq('(', list($._pattern, $._separator), ')'),
    list_pattern: $ => seq('[', list(choice($._pattern, $.rest_pattern), $._separator), ']'),
    rest_pattern: $ => seq('..', optional(choice($.identifier, $.discard))),
    bit_pattern: $ => seq('<<', list($.pattern_segment, $._separator), '>>'),
    pattern_segment: $ => seq($._segment_pattern, optional(seq(':', $.bit_format))),
    _segment_pattern: $ => choice($.identifier, $.discard, $.type_identifier, $.integer, $.float, $.string, $.negative_pattern, $.constructor_pattern, $.tuple_pattern, $.list_pattern, $.bit_pattern, $.prefix_pattern, $.segment_alias_pattern),
    segment_alias_pattern: $ => prec.right(seq($.identifier, '=', $._segment_pattern)),
    typed_pattern: $ => prec.right(2, seq(field('pattern', $._pattern), ':', $._type)),
    alias_pattern: $ => prec.right(0, seq($.identifier, '=', $._pattern)),
    prefix_pattern: $ => seq($.string, '<>', choice($.identifier, $.discard)),
    _type: $ => choice($.named_type, $.value_type, $.type_call, $.integer, $.string, $.discard, $.negative_type, $.type_tuple, $.type_record, $.type_group, $.function_type, $.binary_type),
    named_type: $ => prec(11, seq(optional(seq($.identifier, '.')), $.type_identifier, optional($.type_arguments))),
    value_type: $ => seq(optional(seq($.identifier, '.')), $.identifier),
    type_call: $ => seq(optional(seq($.identifier, '.')), $.identifier, $.type_arguments),
    type_arguments: $ => seq('(', list($._type, $._separator), ')'),
    negative_type: $ => prec(4, seq('-', choice($.integer, $.type_group))),
    binary_type: $ => choice(...[[1, '|'], [2, '&'], [3, '-']].map(([p, op]) => prec.left(p, seq($._type, op, $._type)))),
    type_tuple: $ => seq('(', list($._type, $._separator), ')'),
    type_parameters_list: $ => seq('(', list($.type_parameter, $._separator), ')'),
    type_parameter: $ => seq(optional(seq($.identifier, ':')), $._type),
    type_record: $ => choice(seq('(', $._type_fields, ')'), seq('{', choice('..', $._type_fields), '}')),
    _type_fields: $ => choice(seq($.type_field, repeat(seq($._separator, $.type_field)), optional($._separator)), seq('..', $._type, repeat(seq($._separator, choice($.type_field, $.forgotten_field))), optional($._separator))),
    type_field: $ => seq(field('label', choice($.identifier, $.type_identifier, $.string)), ':', $._type),
    forgotten_field: $ => seq('-', choice($.identifier, $.type_identifier, $.string)),
    type_group: $ => seq('{', $._type, '}'),
    function_type: $ => prec.right(seq($.type_parameters_list, $.return_type)),
    identifier: _ => /_?[a-z][a-z0-9_]*/,
    type_identifier: _ => /[A-Z][A-Za-z0-9]*/,
    discard: _ => /_|__[a-z0-9_]*/,
    integer: _ => /0x[0-9a-fA-F][0-9a-fA-F_]*|0o[0-7][0-7_]*|0b[01][01_]*|[0-9][0-9_]*/,
    float: _ => /[0-9][0-9_]*\.[0-9_]*(e-?[0-9][0-9_]*)?/,
    string: $ => seq('"', repeat(choice($.string_content, $.escape_sequence)), '"'),
    escape_sequence: _ => token.immediate(/\\(u\{[0-9a-fA-F]{1,6}\}|[nrtf"\\])/),
    module_comment: _ => token(prec(3, /\/\/\/\/[^\r\n]*/)),
    doc_comment: _ => token(prec(2, /\/\/\/[^\r\n]*/)),
    comment: _ => token(prec(1, /\/\/[^\r\n]*/)),
  }
});
